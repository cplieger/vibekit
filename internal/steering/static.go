// The agent's tool surface has no resume/retry verb; state only the
// chat-recovery path.
func writeCapabilities(b *strings.Builder, configDir string) {
	b.WriteString("## Capabilities\n\n")
	b.WriteString("- Chat history is stored in `" + configDir + "/chats/*.json` (one file per chat). In the UI, Ctrl+F ")
	b.WriteString("searches the open chat and History → \"Search conversations…\" searches every chat; from ")
	b.WriteString("the shell, grep those files\n")
	b.WriteString("- You can read, write, and edit files in the workspace directly\n")
	b.WriteString("- Undo is per TURN, not per file: kiro-cli snapshots the files its own edit tools write ")
	b.WriteString("(never a shell write, never a manual editor save), and the user's \"Rewind\" on a turn ")
	b.WriteString("footer reverts those files AND drops that prompt and everything after it (a confirm step, ")
	b.WriteString("disabled mid-turn). There is no per-file restore\n")
	b.WriteString("- Shell commands execute in the workspace directory\n")
	b.WriteString("- A paused workflow run recovers through the chat that launched it: this ")
	b.WriteString("server resumes a run its own chat's bridge left paused when that bridge comes ")
	b.WriteString("back, so continuing the conversation is what restarts the run. You have no ")
	b.WriteString("resume or retry tool, so do not plan around one; a run you cannot reach is ")
	b.WriteString("reported to the user, not worked around. What you CAN do to a live run is mark ")
	b.WriteString("a wedged in-flight step completed or failed so the run advances past it\n")
}
