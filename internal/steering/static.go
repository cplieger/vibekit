// command.attachmentBlock (prompt_attachments.go) decides which extensions are
// inlined, and utils-url.ts + file-extensions.ts decide which paths paint; this
// section lies if either set moves.
func writeAttachments(b *strings.Builder, uploadDir, workDir string) {
	b.WriteString("## Images and attachments\n\n")
	b.WriteString("- How a file reaches you: the \"Attach a file\" row (a picker over the file browser; the ")
	b.WriteString("file keeps its path), a drag-drop onto the chat, or a paste into the composer. There is no ")
	b.WriteString("screenshot capture in the app: the user copies a screenshot to the clipboard with the OS ")
	b.WriteString("tool (Win+Shift+S, ⌘⌃⇧4, the GNOME/KDE tools) and pastes it\n")
	b.WriteString("- A pasted image is downscaled to a 2000px long edge, renamed and uploaded to ")
	b.WriteString("`" + uploadDir + "/pasted-YYYY-MM-DDTHH-MM-SS.png` (the stamp is UTC, not `TZ`; `.jpg`/`.webp` ")
	b.WriteString("when the clipboard held one); a pasted FILE keeps its own name in `" + uploadDir + "/`; a pasted ")
	b.WriteString("multi-line TEXT over 50 lines or 10,000 characters becomes `" + uploadDir + "/paste-YYYY-MM-DDTHH-MM-SS.txt` ")
	b.WriteString("and is attached instead of typed (a single line stays in the box whatever its length). Two ")
	b.WriteString("pastes inside one second share a name and the second overwrites. Upload limits: 49 MiB per ")
	b.WriteString("gesture, 25 files\n")
	b.WriteString("- What you receive: `.png/.jpg/.jpeg/.gif/.webp` up to 10 MiB (5 MiB base64, 15 MiB per ")
	b.WriteString("prompt, at most 16 images since the last compaction) arrive as an inline image block: you ")
	b.WriteString("SEE the picture, no tool call is needed, and the block carries NO filename. ")
	b.WriteString("`.pdf/.csv/.doc/.docx/.xls/.xlsx` arrive embedded too, as a `resource` block whose `uri` ")
	b.WriteString("is the file path. Everything else, and any image that misses a limit, arrives as the text ")
	b.WriteString("`Attached file: <path>` with the reason: read that path with your file tools. `.svg` and ")
	b.WriteString("`.avif` are never inlined\n")
	b.WriteString("- So when a user pastes an image: look at it and answer from what you see; do not ")
	b.WriteString("`read_file` it and do not say you cannot see it. When you need the FILE (to edit it, pass ")
	b.WriteString("it to a tool, or re-read it after compaction), the path is not in the prompt: the user's ")
	b.WriteString("message shows the file's pill (name shown, full path on hover), or list `" + uploadDir + "` newest-first ")
	b.WriteString("(`ls -t " + uploadDir + " | head`) and take the `pasted-<timestamp>` that matches. A ")
	b.WriteString("`paste-*.txt` attachment is text the composer spilled out of the prompt: read it, it IS ")
	b.WriteString("part of the request\n")
	b.WriteString("- Failure modes: an image the backend refuses (pixel dimensions or image count over its ")
	b.WriteString("limit, an unsupported or mismatched format; vibekit caps bytes before sending and does not ")
	b.WriteString("check whether the model takes images, and only a PASTED image is downscaled, so in practice ")
	b.WriteString("a dimension refusal comes from a file attached from disk) ends the turn with \"The ")
	b.WriteString("request was refused as sent. Resending it unchanged will fail the same way\": shrink or ")
	b.WriteString("drop the image, or use Rewind to remove an earlier prompt image, or reopen the chat to ")
	b.WriteString("clear an image a tool returned. A `.txt` where the user expected an image means the ")
	b.WriteString("clipboard carried text, not pixels\n")
	b.WriteString("- To SHOW the user an image you produced, write it as markdown: ")
	b.WriteString("`![label](" + workDir + "/out/shot.png)`. That renders inline; a bare path is prose. The ")
	b.WriteString("path must be absolute and under `" + workDir + "/` or `" + uploadDir + "/` (never ")
	b.WriteString("`/config/`), and png/jpg/jpeg/gif/webp/svg/avif/ico/bmp all paint. Audio ")
	b.WriteString("(mp3/wav/ogg/m4a/flac/aac/opus) in the same position gets a player, any other file a ")
	b.WriteString("download link\n\n")
}

